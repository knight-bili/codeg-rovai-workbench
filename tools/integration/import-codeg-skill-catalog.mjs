import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// Read only fixed Git objects. Never run donor scripts or scan a user's Home.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const donor=process.argv[2];
assert(donor && path.isAbsolute(donor),'Provide an absolute, local Codeg donor checkout');
const source=JSON.parse(readFileSync(path.join(root,'integration/sources.lock.json'),'utf8')).sources.find(x=>x.id==='codeg');
const git=(...args)=>execFileSync('git',['-C',donor,...args],{maxBuffer:8*1024*1024});
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const sourceRoots=['src-tauri/experts','src-tauri/science','src-tauri/genui','src-tauri/src/commands/office_tools.rs','LICENSE'];
const objects=git('ls-tree','-rz',source.commit,'--',...sourceRoots).toString('utf8').split('\0').filter(Boolean).map(line=>{
  const [header,sourcePath]=line.split('\t');const [mode,kind,blob]=header.split(' ');
  assert(kind==='blob' && ['100644','100755'].includes(mode),'Only regular fixed source files are admitted');
  assert(!sourcePath.split('/').some(p=>p==='..' || p==='.' || !p),'Invalid source path');
  return {sourcePath,mode,blob};
}).sort((a,b)=>a.sourcePath.localeCompare(b.sourcePath,'en'));
const target=path.join(root,'crates/rovai-core/resources/codeg-skill-packs');
const put=(relative,bytes)=>{
  const file=path.join(target,relative);assert(file.startsWith(target+path.sep));
  if(existsSync(file)){assert.deepEqual(readFileSync(file),Buffer.from(bytes),`Existing generated resource changed: ${relative}`);return;}
  mkdirSync(path.dirname(file),{recursive:true});writeFileSync(file,bytes);
};
const files=objects.map(object=>{
  const bytes=git('cat-file','blob',object.blob);
  assert.equal(createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex'),object.blob);
  const file=object.sourcePath==='LICENSE'?'LICENSE':object.sourcePath==='src-tauri/src/commands/office_tools.rs'?'source-inputs/office_tools.rs':object.sourcePath.slice('src-tauri/'.length);
  put(file,bytes);return {...object,path:file,bytes:bytes.length,sha256:sha256(bytes)};
});
// Office has no static guide in the donor. Preserve its explicit CLI identifiers
// and metadata; do not invent content or invoke/load/install an external binary.
const officeSource=readFileSync(path.join(target,'source-inputs/office_tools.rs'),'utf8');
const office=[];
for(const match of officeSource.split('const SKILLS: &[SkillDef] = &[')[1].split('\n];')[0].matchAll(/SkillDef \{([\s\S]*?)\n    \}/g)){
  const entry={};for(const field of match[1].matchAll(/(\w+): ("(?:[^"\\]|\\.)*"|\d+),/g))entry[field[1]]=JSON.parse(field[2]);
  assert.deepEqual(Object.keys(entry).sort(),['id','load_id','category','icon','sort_order','en_name','en_desc','zh_name','zh_desc'].sort());
  office.push({id:entry.id,loadId:entry.load_id,category:entry.category,icon:entry.icon,sortOrder:entry.sort_order,displayName:{en:entry.en_name,'zh-CN':entry.zh_name},description:{en:entry.en_desc,'zh-CN':entry.zh_desc}});
}
assert.equal(office.length,9);
put('office.json',JSON.stringify(office,null,2)+'\n');
put('manifest.json',JSON.stringify({schemaVersion:1,repository:source.repository,commit:source.commit,license:source.license,files},null,2)+'\n');
const embeds=files.map(x=>`    (${JSON.stringify(x.path)}, include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/resources/codeg-skill-packs/${x.path}"))),`).join('\n');
put('files.rs',`// Generated by tools/integration/import-codeg-skill-catalog.mjs from fixed Git objects.\n// Data only; embedded scripts are never executed by catalog reads.\npub(super) const FILES: &[(&str, &[u8])] = &[\n${embeds}\n];\n`);
console.log(JSON.stringify({sourceCommit:source.commit,sourceFiles:files.length,bytes:files.reduce((sum,x)=>sum+x.bytes,0),officeDependencies:office.length}));
