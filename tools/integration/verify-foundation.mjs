import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ts from 'typescript';
import { execFileSync } from 'node:child_process';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const text=(p)=>readFileSync(path.join(root,p),'utf8');
const json=(p)=>JSON.parse(text(p));
const contract=json('integration/foundation/source-protocol.json');
const source=json('integration/sources.lock.json').sources.find(x=>x.id==='rovai-ai');
const sourceText=(p)=>execFileSync('git',['show',`${source.commit}:${p}`],{cwd:root,encoding:'utf8',maxBuffer:20*1024*1024});
const web=sourceText('crates/rovai-web/src/lib.rs'), db=sourceText('crates/rovai-core/src/db.rs');
const enumSource=sourceText('crates/rovai-web/src/operations.rs').split('pub enum Operation {')[1].split('\n}')[0];
const operations=Array.from(enumSource.matchAll(/rename\s*=\s*"([^"]+)"/g),x=>x[1]);
assert.equal(contract.hostWebProtocolVersion,Number(web.match(/HOST_WEB_PROTOCOL_VERSION: u32 = (\d+)/)[1]));
assert.equal(contract.coreDataContractVersion,db.match(/CURRENT_DATA_CONTRACT_VERSION: &str = "([^"]+)"/)[1]);
assert.equal(contract.coreProjectionSchemaVersion,Number(db.match(/CURRENT_PROJECTION_SCHEMA_VERSION: i64 = (\d+)/)[1]));
assert.deepEqual(contract.canonicalWebOperations,operations);
const command=sourceText('crates/rovai-core/src/command.rs');
const envelope=command.split('pub struct CommandEnvelope<P> {')[1].split('\n}')[0];
const camelCase=(field)=>field.replace(/_([a-z])/g,(_,letter)=>letter.toUpperCase());
assert.deepEqual(contract.coreEnvelopeFields,Array.from(envelope.matchAll(/pub (\w+):/g),x=>camelCase(x[1])));
assert.match(envelope,/expected_versions: Vec<ExpectedVersion>/);
assert.match(command,/serde\(tag = "type", rename_all = "snake_case"\)/);
const request=web.split('struct OperationRequest {')[1].split('\n}')[0];
assert.deepEqual(contract.webOperationRequestFields,Array.from(request.matchAll(/^\s*(\w+):/gm),x=>x[1]));
assert.match(web,/#\[serde\(deny_unknown_fields\)\]\s*struct OperationRequest/);
assert.equal(contract.sourceCommit,source.commit);
// The locked-source evidence is historical. Current Core evolution has its own
// explicit snapshot; widening a catalog must not relabel an old binary's proof.
const current=json('integration/foundation/current-protocol.json');
const currentWeb=text('crates/rovai-web/src/lib.rs'), currentDb=text('crates/rovai-core/src/db.rs');
assert.equal(current.hostWebProtocolVersion,Number(currentWeb.match(/HOST_WEB_PROTOCOL_VERSION: u32 = (\d+)/)[1]));
assert.equal(current.coreDataContractVersion,currentDb.match(/CURRENT_DATA_CONTRACT_VERSION: &str = "([^"]+)"/)[1]);
assert.equal(current.coreProjectionSchemaVersion,Number(currentDb.match(/CURRENT_PROJECTION_SCHEMA_VERSION: i64 = (\d+)/)[1]));
assert.deepEqual(current.canonicalWebOperations,Array.from(text('crates/rovai-web/src/operations.rs').split('pub enum Operation {')[1].split('\n}')[0].matchAll(/rename\s*=\s*"([^"]+)"/g),x=>x[1]));
assert.equal(current.sourceCommit,source.commit);
const cases=json('integration/foundation/protocol-cases.json');
assert.equal(new Set(cases.map(x=>x.id)).size,cases.length);
assert(cases.some(x=>x.saveSession && x.body.protocolVersion===contract.hostWebProtocolVersion));
assert(cases.some(x=>x.expectedHttp===409 && x.body.protocolVersion!==contract.hostWebProtocolVersion));
for(const c of cases.filter(x=>x.path==='request' && x.expectedHttp===200))assert(operations.includes(c.body.operation));
assert(cases.some(x=>x.path==='request' && !operations.includes(x.body.operation) && x.expectedHttp===400));
const migration=json('integration/foundation/migration-fixtures.json');
assert.equal(migration.kind,'design_fixture_not_a_production_migration');
assert(migration.intendedMapping.scopeKeys.includes('sourceHost') && migration.cases.every(x=>x.status==='not_run'));
// 直接执行源合同里的身份校验，保留其UUIDv7和RFC variant检查。
const identitySource='export const THREAD_ID_PATTERN'+text('packages/contracts/src/index.ts').split('export const THREAD_ID_PATTERN')[1].split('/** Legacy input helper;')[0];
const identityJs=ts.transpileModule(identitySource,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {isThreadId}=await import(`data:text/javascript,${encodeURIComponent(identityJs)}`);
assert(isThreadId(migration.intendedMapping.publicThreadRef),'导入目标必须是Core公共Thread身份，不能使用普通UUID或供应商Session');
console.log(JSON.stringify({status:'passed',kind:'source_contract_and_fixture_consistency',canonicalOperations:operations.length,httpCases:cases.length,migrationDesignCases:migration.cases.length,liveHostExecution:'not_run_by_this_checker'}));
